CREATE TABLE stations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    description text NOT NULL DEFAULT '',
    enabled boolean NOT NULL DEFAULT true
);

CREATE TABLE tracks (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id integer NOT NULL REFERENCES stations(id),
    title text NOT NULL,
    artist text NOT NULL,
    duration_ms integer NOT NULL CHECK (duration_ms > 0),
    enabled boolean NOT NULL DEFAULT true,
    UNIQUE (id, station_id)
);

CREATE TABLE track_audio (
    track_id integer PRIMARY KEY REFERENCES tracks(id),
    content_type text NOT NULL,
    data bytea NOT NULL CHECK (octet_length(data) > 0)
);

CREATE TABLE station_playback (
    station_id integer PRIMARY KEY REFERENCES stations(id),
    current_track_id integer,
    position_ms integer NOT NULL DEFAULT 0 CHECK (position_ms >= 0),
    status text NOT NULL DEFAULT 'idle'
        CHECK (status IN ('idle', 'loading', 'playing', 'paused', 'error')),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (current_track_id, station_id) REFERENCES tracks(id, station_id),
    CHECK (
        (status = 'idle' AND current_track_id IS NULL AND position_ms = 0)
        OR (status <> 'idle' AND current_track_id IS NOT NULL)
    )
);

CREATE INDEX tracks_available ON tracks(station_id) WHERE enabled;
